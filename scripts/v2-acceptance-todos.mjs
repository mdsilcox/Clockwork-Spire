// Writes tests/v2/*.acceptance.test.ts: one pending test per v2 acceptance criterion (docs/acceptance.md sections 9 to 17).
// The build phase that owns a criterion replaces its `it.todo` with a real test (never weaker than the criterion text).
// Rerun after editing the criteria: node scripts/v2-acceptance-todos.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'fs';

const src = readFileSync('docs/acceptance.md', 'utf8').split('\n');
const sections = [];
let cur = null;
for (const line of src) {
  const h = line.match(/^## (\d+)\. (.+)$/);
  if (h) {
    cur = Number(h[1]) >= 9 ? { n: Number(h[1]), title: h[2], rows: [] } : null;
    if (cur) sections.push(cur);
    continue;
  }
  if (!cur || !line.startsWith('| ')) continue;
  const cells = line.split('|').slice(1, -1).map((c) => c.trim());
  if (cells.length < 6 || cells[0] === 'id' || /^-+$/.test(cells[0])) continue;
  const [id, given, when, then, kind] = cells;
  cur.rows.push({ id, given, when, then, kind });
}
const slug = (t) => t.toLowerCase().replace(/\(.*?\)/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);
mkdirSync('tests/v2', { recursive: true });
let total = 0;
for (const s of sections) {
  const esc = (t) => t.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const body = s.rows
    .map((r) => `  it.todo('${esc(`${r.id} [${r.kind}] Given ${r.given}; when ${r.when}; then ${r.then}`)}');`)
    .join('\n');
  total += s.rows.length;
  const file = `tests/v2/${String(s.n).padStart(2, '0')}-${slug(s.title)}.acceptance.test.ts`;
  writeFileSync(
    file,
    `// v2 acceptance, docs/acceptance.md section ${s.n}: ${s.title}. Generated by scripts/v2-acceptance-todos.mjs.\n` +
      `// Each todo becomes a real test in the build phase that owns it (E kinds move to e2e/).\n` +
      `import { describe, it } from 'vitest';\n\ndescribe('v2 ${s.n}. ${esc(s.title)}', () => {\n${body}\n});\n`,
  );
}
console.log(`${sections.length} files, ${total} criteria`);
